    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
      
        String[][] record = {{txtName.getText(), txtLocation.getText(), comboboxYears.getSelectedItem().toString()}};
        for (int r = 0; r< record.length; r++) {
            for (int c = 0; c < record.length; c++){
                 javax.swing.JOptionPane.showMessageDialog(this, record[r], "Message", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
        }
  
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText();
        String location = txtLocation.getText();
        String years = comboboxYears.getSelectedItem().toString();
        String output = "Hospital Name: " + name + "\n" + "Hospital Location: " + location + "\n"
                + "Years since inspection: " +years + "\n*******************************************************";
        
        rcd = new HospitalRecords(name, location, years, output);
        String report = rcd.getReport();

        txtArea.setText(output);
    }//GEN-LAST:event_btnPrintActionPerformed

